#!/usr/bin/env python3
"""Fetch Semantic Scholar citation counts for all publications and cache them
in _data/citations.yml, so the site shows counts even when the API is down.

Counts the API does not return are kept from the previous run: either the
existing _data/citations.yml, or the counts published by the live site at
$PREVIOUS_CITATIONS_URL (used in CI, where the data file is not committed).
"""
import json
import os
import pathlib
import re
import sys
import time
import urllib.error
import urllib.request

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "_data" / "citations.yml"
API = "https://api.semanticscholar.org/graph/v1/paper/batch?fields=citationCount"

ids = sorted({
    m.group(1).lower()
    for f in (ROOT / "_publications").rglob("*.md")
    if (m := re.search(r"^semantic_scholar_id:\s*([0-9a-fA-F]+)", f.read_text(), re.M))
})

# Previous counts, used for any paper the API does not answer for
counts = {}
if os.environ.get("PREVIOUS_CITATIONS_URL"):
    try:
        with urllib.request.urlopen(os.environ["PREVIOUS_CITATIONS_URL"], timeout=30) as r:
            counts.update(json.load(r) or {})
    except (urllib.error.URLError, ValueError) as e:
        print(f"Could not load previous counts: {e}", file=sys.stderr)
if OUT.exists():
    counts.update(dict(re.findall(r"^([0-9a-f]+):\s*(\d+)", OUT.read_text(), re.M)))
counts = {k: int(v) for k, v in counts.items()}


def fetch():
    headers = {"Content-Type": "application/json"}
    for attempt in range(6):
        req = urllib.request.Request(API, data=json.dumps({"ids": ids}).encode(), headers=headers)
        try:
            with urllib.request.urlopen(req, timeout=30) as r:
                return json.load(r)
        except urllib.error.HTTPError as e:
            if e.code != 429:
                print(f"Semantic Scholar API error: {e}", file=sys.stderr)
                return None
            wait = 10 * (attempt + 1)
            print(f"Rate limited, retrying in {wait}s...", file=sys.stderr)
            time.sleep(wait)
        except urllib.error.URLError as e:
            print(f"Semantic Scholar API unreachable: {e}", file=sys.stderr)
            return None
    print("Semantic Scholar API kept rate limiting.", file=sys.stderr)
    return None


papers = fetch()
for paper in papers or []:
    if paper and paper.get("citationCount") is not None:
        counts[paper["paperId"]] = paper["citationCount"]

lines = ["# Generated by scripts/update_citations.py. Do not edit by hand."]
lines += [f"{k}: {counts[k]}" for k in ids if k in counts]
OUT.write_text("\n".join(lines) + "\n")
print(OUT.read_text())

if papers is None:
    sys.exit("Kept previous counts because the API request failed.")
